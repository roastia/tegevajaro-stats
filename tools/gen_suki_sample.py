def fill(s):
    return s.replace('{who}', R.choice(WHO)).replace('{place}', R.choice(PLACE)).replace('{food}', R.choice(FOOD)).replace('{when}', R.choice(WHEN))

def pick(tag, k, used):
    pool = [s for s in P[tag] if s not in used] or P[tag]
    out = R.sample(pool, min(k, len(pool)))
    used.update(out)
    return [fill(s) for s in out]

def short(tags):
    return pick(tags[0], 1, set())[0]

def medium(tags):
    used = set(); out = []
    for t in tags: out += pick(t, R.randint(1, 2), used)
    return ''.join(out)

def long(tags):
    used = set(); mids = [LONG_MID[j] for j in sorted(R.sample(range(len(LONG_MID)), 12))]  # 話の順番はくずさない
    paras = [[R.choice(LONG_OPEN)]]
    body = lambda: '\n\n'.join(''.join(p) for p in paras)
    cur = paras[0]
    i = 0
    while len(body()) < 545:
        if R.random() < .45 and i < len(mids):
            s = fill(mids[i]); i += 1
        else:
            s = pick(R.choice(tags), 1, used)[0]
        cur.append(s)
        if len(cur) >= R.randint(3, 5): cur = []; paras.append(cur)
    paras = [p for p in paras if p]
    close = R.choice(LONG_CLOSE)
    paras.append([close])
    text = '\n\n'.join(''.join(p) for p in paras)
    while len(text) > 600:  # 長すぎたら、まんなかの文を一つずつ減らす
        big = max(paras[:-1], key=len)
        big.pop(R.randrange(1, len(big)) if len(big) > 1 else 0)
        paras = [p for p in paras if p]
        text = '\n\n'.join(''.join(p) for p in paras)
    return text

